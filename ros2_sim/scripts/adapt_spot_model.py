#!/usr/bin/env python3
"""
adapt_spot_model.py — spot_stack's Spot SDF → `spot_evader` model for ros2_sim
-------------------------------------------------------------------------------
Reads ../spot_stack/spot_description/models/spot/model.sdf (Gazebo Fortress /
"ignition" era, the same generation as this package's image, so plugin names
are kept as-is) and writes ../models/spot_evader/model.sdf:

  * model renamed to "spot_evader"; every `model/spot/` topic becomes
    `model/spot_evader/`, so the launch file bridges
    /model/spot_evader/odometry (-> /evader/odom) and
    /model/spot_evader/joint_trajectory (<- CHAMP) exactly like it does for
    the Pioneer's /model/simple_ground_robot/* topics
  * <odom_frame> set to `world`, matching the Pioneer and X4 models and
    RViz's Fixed Frame (see the odom_frame note in models/pioneer3at)
  * all <sensor> blocks removed (lidar/cameras/IMU/foot contacts are unused
    here and would need the world-level sensors system + rendering)
  * the now-pointless imu-system plugin dropped
  * <collide_bitmask>0x01</collide_bitmask> on every collision, so Spot
    collides with walls/ground but never with the drone

Mesh URIs (package://spot_description/...) are left untouched; the launch
file puts spot_description's share parent on the Gazebo resource path.

Copied from CodeICRA25/icra25_ros2/scripts/adapt_spot_model.py (there the
model is named "evader" and the odom frame "evader/odom").

Usage:  python3 adapt_spot_model.py     (rerun only if spot_stack changes)
"""

import os
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
SRC = os.path.join(PKG, 'spot_stack', 'spot_description',
                   'models', 'spot', 'model.sdf')
OUT_DIR = os.path.join(PKG, 'models', 'spot_evader')
OUT = os.path.join(OUT_DIR, 'model.sdf')
NAME = 'spot_evader'


def main():
    with open(SRC) as f:
        text = f.read()
    text = text.replace('model/spot/', f'model/{NAME}/')
    text = text.replace('<odom_frame>/odom_spot</odom_frame>',
                        '<odom_frame>world</odom_frame>')

    root = ET.fromstring(text)
    model = root.find('model')
    model.set('name', NAME)

    removed = 0
    for parent in model.iter():
        for sensor in list(parent.findall('sensor')):
            parent.remove(sensor)
            removed += 1
    for plugin in list(model.findall('plugin')):
        if 'imu-system' in (plugin.get('filename') or ''):
            model.remove(plugin)

    masked = 0
    for collision in model.iter('collision'):
        surface = collision.find('surface')
        if surface is None:
            surface = ET.SubElement(collision, 'surface')
        contact = surface.find('contact')
        if contact is None:
            contact = ET.SubElement(surface, 'contact')
        if contact.find('collide_bitmask') is None:
            ET.SubElement(contact, 'collide_bitmask').text = '0x01'
            masked += 1

    os.makedirs(OUT_DIR, exist_ok=True)
    header = ('<?xml version="1.0"?>\n'
              '<!-- generated by scripts/adapt_spot_model.py from '
              'spot_stack/spot_description\n'
              '     (do not edit by hand - rerun the script instead) -->\n')
    with open(OUT, 'w') as f:
        f.write(header + ET.tostring(root, encoding='unicode'))
    with open(os.path.join(OUT_DIR, 'model.config'), 'w') as f:
        f.write('<?xml version="1.0"?>\n<model>\n'
                f'  <name>{NAME}</name>\n  <version>1.0</version>\n'
                '  <sdf version="1.9">model.sdf</sdf>\n'
                '  <description>Boston Dynamics Spot (spot_stack/spot_description, '
                'adapted by scripts/adapt_spot_model.py) as the walking '
                'evader.</description>\n</model>\n')
    print(f'wrote {OUT}: {removed} sensors removed, {masked} collisions masked')


if __name__ == '__main__':
    main()
